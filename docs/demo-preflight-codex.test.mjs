import test from 'node:test';
import assert from 'node:assert/strict';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

for (const mode of ['missing', 'mismatch', 'child-write']) test({
  missing: 'missing credentials cannot be generated by preflight',
  mismatch: 'mismatched environment cannot rewrite credentials or print their values',
  'child-write': 'baseline child cannot write the credential store even after passing the token guard',
}[mode], () => {
  const root = mkdtempSync(join(tmpdir(), 'tacit-codex-preflight-test-'));
  try {
    mkdirSync(join(root, 'docs'));
    copyFileSync(new URL('./demo-preflight-codex.mjs', import.meta.url), join(root, 'docs/demo-preflight-codex.mjs'));
    const secret = join(root, 'server/data/secrets.json');
    const original = JSON.stringify({ userToken: 'TEST-ONLY-STORED-CANARY', callerToken: 'TEST-ONLY-CALLER-CANARY' });
    if (mode !== 'missing') { mkdirSync(join(root, 'server/data'), { recursive: true }); writeFileSync(secret, original); }
    if (mode === 'child-write') {
      mkdirSync(join(root, 'server/node_modules/tsx/dist'), { recursive: true });
      writeFileSync(join(root, 'server/node_modules/tsx/dist/cli.mjs'),
        "import { writeFileSync } from 'node:fs'; writeFileSync('server/data/secrets.json', 'CHANGED');\n");
    }
    const result = spawnSync(process.execPath, ['docs/demo-preflight-codex.mjs'], {
      cwd: root, encoding: 'utf8', timeout: 15000,
      env: { PATH: process.env.PATH, PORT: '1', TACIT_USER_TOKEN: mode === 'child-write' ? 'TEST-ONLY-STORED-CANARY' : 'TEST-ONLY-ENV-CANARY' },
    });
    assert.equal(result.status, 1);
    assert.match(result.stdout, /FAIL\s+existing preflight/);
    assert.doesNotMatch(result.stdout + result.stderr, /TEST-ONLY-.*CANARY/);
    assert.equal(existsSync(secret), mode !== 'missing');
    if (mode !== 'missing') assert.equal(readFileSync(secret, 'utf8'), original);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
