/** Synthesized test audio through the actual browser microphone/worklet path. NOT a physical microphone/speaker test. */
import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import { readFile, mkdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import AxeBuilder from '@axe-core/playwright';
const base = process.env.TACIT_WEB_URL ?? 'http://localhost:5173';
const artifacts = new URL('../artifacts/ui-review/',import.meta.url);
await mkdir(artifacts,{recursive:true});
const capture = async (page,name) => { const active=await page.locator('video').evaluateAll(videos=>videos.some(video=>video.srcObject)); return page.screenshot({path:fileURLToPath(new URL(name,artifacts)),fullPage:true,animations:'disabled',mask:active?[page.locator('video'),page.locator('canvas')]:[],maskColor:'#1b221d'}); };
const folder = new URL('./.audio-smoke/', import.meta.url);
await mkdir(folder,{recursive:true});
const aiff=fileURLToPath(new URL('input.aiff',folder));
const wav=fileURLToPath(new URL('input.wav',folder));
execFileSync('say',['-o',aiff,'Hey, it is Sam. Are we still on for dinner tonight?']);
execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-i',aiff,'-ac','1','-ar','48000','-c:a','pcm_s16le',wav]);
const secrets=JSON.parse(await readFile(new URL('../../server/data/secrets.json',import.meta.url),'utf8'));
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream',`--use-file-for-fake-audio-capture=${wav}%noloop`,'--autoplay-policy=no-user-gesture-required']});
const context=await browser.newContext({viewport:{width:1440,height:900},permissions:['microphone']});
await context.addInitScript(({user,caller})=>{sessionStorage.setItem('tacit-access-user',user);sessionStorage.setItem('tacit-access-caller',caller);},{user:secrets.userToken,caller:secrets.callerToken});
const user=await context.newPage();const errors=[];const audits=[];
const audit=async(page,state)=>{const report=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze();audits.push({state,violations:report.violations.map(v=>({id:v.id,impact:v.impact,help:v.help,targets:v.nodes.map(n=>n.target)}))});};
user.on('pageerror',e=>errors.push(e.message));
let caller;
let confirmed=false;
let audioBeforeConfirmation=0;
let audioAfterConfirmation=0;
try {
  await user.goto(base);await user.getByText('System connected',{exact:true}).waitFor();
  assert.equal(await user.getByRole('button',{name:'End call',exact:true}).count(),0,'another call is active; do not interrupt it');
  await capture(user,'01-workspace.png');
  caller=await context.newPage();caller.on('pageerror',e=>errors.push(e.message));
  caller.on('websocket',socket=>socket.on('framereceived',event=>{if(typeof event.payload!=='string'){if(confirmed)audioAfterConfirmation++;else audioBeforeConfirmation++;}}));
  await caller.goto(`${base}/#caller`);await capture(caller,'07-caller-ready.png');await caller.getByRole('button',{name:'Call TACIT',exact:true}).click();
  await caller.getByText('Call connected',{exact:true}).waitFor();
  await caller.getByRole('button',{name:'Enable microphone',exact:true}).click();
  await caller.getByRole('button',{name:'Pause microphone',exact:true}).waitFor();
  await capture(caller,'08-caller-microphone-streaming.png');
  await user.getByRole('button',{name:/^01 /}).waitFor({timeout:45000});
  const transcript=await user.locator('.caller-quote').innerText();const model=await user.locator('.reply-meta>span').innerText();
  assert.match(transcript,/dinner|tonight/i);
  assert.match(model,/gemini/i);assert.doesNotMatch(model,/local-rules/i);
  await caller.getByRole('button',{name:'Pause microphone',exact:true}).click();
  await capture(user,'02-three-gemini-candidates.png');
  await user.setViewportSize({width:1280,height:800});
  await capture(user,'15-laptop-candidates.png');
  await user.setViewportSize({width:390,height:844});
  await capture(user,'16-mobile-candidates.png');
  assert.equal(await user.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'mobile workspace must not overflow horizontally');
  await user.setViewportSize({width:1440,height:900});
  await audit(user,'real Gemini candidates');
  await audit(caller,'caller connected after microphone');
  await user.getByRole('button',{name:/^01 /}).focus();
  await capture(user,'03-candidate-keyboard-focus.png');
  await user.getByRole('button',{name:/^01 /}).click();
  await capture(user,'04-proposed-response.png');
  await user.getByRole('button',{name:'Confirm & speak',exact:false}).waitFor();
  await capture(user,'05-confirmation-ready.png');
  assert.equal(audioBeforeConfirmation,0,'no audio may arrive before explicit confirmation');
  confirmed=true;
  await user.getByRole('button',{name:'Confirm & speak',exact:false}).click();
  await user.locator('.speech-status').filter({hasText:'Caller device reported playback complete'}).waitFor({timeout:30000});
  await capture(user,'06-playback-acknowledged.png');
  await capture(caller,'09-caller-playback-complete.png');
  await user.getByRole('button',{name:'Diagnostics',exact:true}).click();
  await capture(user,'10-diagnostics.png');
  const stages=await user.locator('.diagnostic-grid>div').nth(2).innerText();
  const micEvidence=await caller.locator('.caller-mic').innerText();
  await writeFile(new URL('accessibility-results.json',artifacts),JSON.stringify(audits,null,2)+'\n');
  assert.ok(audits.every(a=>a.violations.length===0),'audited live states must have no axe WCAG A/AA violations');
  assert.deepEqual(errors,[]);
  assert.ok(audioAfterConfirmation>0,'confirmed reply must produce real audio');
  const result={audioBeforeConfirmation,audioAfterConfirmation,source:'automated synthesized microphone fixture; NOT physical microphone/speaker',transcript,model,micEvidence,stages,playback:'actual HTMLAudioElement ended acknowledgment',applicationExceptions:errors};
  console.log(JSON.stringify(result,null,2));
  await writeFile(new URL('test-results.json',artifacts),JSON.stringify(result,null,2)+'\n');
  await caller.getByRole('button',{name:'End call',exact:true}).click();
} finally {await browser.close();await rm(folder,{recursive:true,force:true});}
